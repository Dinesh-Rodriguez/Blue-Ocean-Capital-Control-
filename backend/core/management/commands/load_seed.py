import json
from pathlib import Path
from django.db import connection
from django.contrib.auth import get_user_model
from django.core.management.base import BaseCommand
from core.models import Organization, Property, UserProfile, Budget, Project, ApprovalEvent

class Command(BaseCommand):
    help = "Load JSON generated by harness/seed.py"
    def add_arguments(self, parser):
        parser.add_argument("directory", type=Path)
    def handle(self, directory, **kwargs):
        data = {name: json.loads((directory / f"{name}.json").read_text()) for name in
                ("organizations", "properties", "users", "budgets", "projects", "approval_events")}
        profit_by_org = {1: 18400000, 2: 22750000, 3: 31600000, 4: 14800000, 5: 26400000, 6: 19750000, 7: 35200000, 8: 24100000}
        orgs = {row["id"]: Organization.objects.update_or_create(
            id=row["id"],
            defaults={"name": row["name"], "slug": row["slug"], "profit_amount": profit_by_org.get(row["id"], 0)},
        )[0] for row in data["organizations"]}
        props = {row["id"]: Property.objects.update_or_create(id=row["id"], defaults={"organization": orgs[row["org_id"]], "name": row["name"], "code": row["code"]})[0] for row in data["properties"]}
        User = get_user_model()
        for row in data["users"]:
            user, _ = User.objects.get_or_create(username=row["email"], defaults={"email": row["email"]})
            user.set_password(row["password"]); user.save()
            profile, _ = UserProfile.objects.update_or_create(user=user, defaults={"organization": orgs[row["org_id"]], "role": row["role"]})
            profile.properties.set([props[pid] for pid in row["property_ids"]])
        for row in data["budgets"]:
            Budget.objects.update_or_create(id=row["id"], defaults={"organization": orgs[row["org_id"]], "property": props[row["property_id"]], "fiscal_period": row["fiscal_period"], "allocated_amount": row["allocated_amount"]})
        for row in data["projects"]:
            Project.objects.update_or_create(id=row["id"], defaults={"organization": orgs[row["org_id"]], "property": props[row["property_id"]], "title": row["title"], "category": row["category"], "fiscal_period": row["fiscal_period"], "budget_amount": row["budget_amount"], "actual_cost": row["actual_cost"], "status": row["status"], "created_at": row["created_at"]})
        for row in data["approval_events"]:
            project = Project.objects.get(id=row["project_id"])
            actor = User.objects.filter(profile__organization_id=row["org_id"]).first()
            ApprovalEvent.objects.get_or_create(id=row["id"], defaults={"project": project, "organization": orgs[row["org_id"]], "property": props[row["property_id"]], "actor": actor, "from_status": "", "to_status": row["to_status"], "created_at": row["at"]})
        with connection.cursor() as cursor:
            cursor.execute(
                "SELECT setval(pg_get_serial_sequence('core_project', 'id'), "
                "COALESCE((SELECT MAX(id) FROM core_project), 1), true)"
            )
            cursor.execute(
                "SELECT setval(pg_get_serial_sequence('core_approvalevent', 'id'), "
                "COALESCE((SELECT MAX(id) FROM core_approvalevent), 1), true)"
            )
        self.stdout.write(self.style.SUCCESS("Seed data loaded"))
